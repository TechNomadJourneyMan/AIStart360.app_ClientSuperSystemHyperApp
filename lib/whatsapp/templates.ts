/**
 * lib/whatsapp/templates.ts — catalogue of the WhatsApp message templates.
 *
 * Business-initiated WhatsApp messages outside the 24-hour customer service
 * window must use a template approved by Meta (Cloud API › Message templates:
 * https://developers.facebook.com/documentation/business-messaging/whatsapp/templates/overview).
 * Every template below has to be submitted in WhatsApp Manager with exactly
 * this name, category, language (WHATSAPP_TEMPLATE_LANG, default 'ru'), body
 * text and button — the list for the owner is in
 * docs/platform/06-integrations.md («WhatsApp: шаблоны для одобрения»).
 *
 * The code sends only the variables. A mismatch between the approved template
 * and the variables sent here makes Meta reject the message (error 132000
 * family), which the outbox records as a permanent failure.
 *
 * Variable rules (Meta): a text parameter may not contain new lines, tabs or
 * more than four consecutive spaces; a body may not start or end with a
 * variable. sanitizeParam enforces the first rule, the bodies the second.
 *
 * URL buttons are dynamic: the approved URL is `<site>/{{1}}` (site =
 * NEXT_PUBLIC_APP_URL of production), the code sends the path suffix.
 */
import { getSiteUrl } from '@/lib/site-url'

export type TemplateKey = 'digest' | 'expert_notification' | 'report_review' | 'staff_alert' | 'phone_verification'

export interface TemplateDefinition {
  name: TemplateKey
  category: 'UTILITY' | 'AUTHENTICATION'
  /** Body text to submit for approval (AUTHENTICATION: preset by Meta, shown for reference). */
  body: string
  /** Meaning of {{1}}, {{2}}, … in order. */
  variables: string[]
  /** Example values for the submission form. */
  examples: string[]
  button:
    | { type: 'url'; text: string; url: string; example: string }
    | { type: 'copy_code'; text: string }
  /** AUTHENTICATION extras chosen in WhatsApp Manager. */
  auth?: { securityRecommendation: true; codeExpirationMinutes: number }
}

