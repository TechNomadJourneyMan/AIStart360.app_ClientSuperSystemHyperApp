/** Meta rejects parameters with new lines, tabs or > 4 consecutive spaces. */
export function sanitizeParam(value: unknown, max = 300, fallback = '—'): string {
  const s = String(value ?? '')
    .replace(/[\r\n\t]+/g, ' · ')
    .replace(/\s{2,}/g, ' ')
    .trim()
  const out = s.length > max ? `${s.slice(0, max - 1).trimEnd()}…` : s
  return out || fallback
}

/** Path suffix for a dynamic URL button: '/admin-giga-panel/x?y=1' → 'admin-giga-panel/x?y=1'. */
export function urlSuffix(path: string | null | undefined, fallback: string): string {
  const raw = String(path ?? '').trim()
  if (!raw || /^https?:\/\//i.test(raw) || /\s/.test(raw)) return fallback
  const s = raw.replace(/^\/+/, '')
  return s.length > 0 && s.length <= 500 ? s : fallback
}

/** What the outbox stores and the sender turns into Cloud API components. */
export interface TemplatePayload {
  template: TemplateKey
  body: string[]
  buttons: Array<{ index: number; text: string }>
  /** Plain text for the staff-only WhatsApp Web bridge fallback. */
  fallbackText: string
}

function render(def: TemplateDefinition, body: string[], link: string | null): string {
  let text = def.body
  body.forEach((v, i) => { text = text.split(`{{${i + 1}}}`).join(v) })
  return link ? `${text}\n${link}` : text
}

function urlPayload(key: TemplateKey, body: string[], suffix: string): TemplatePayload {
  const def = WHATSAPP_TEMPLATES[key]
  return { template: key, body, buttons: [{ index: 0, text: suffix }], fallbackText: render(def, body, getSiteUrl(`/${suffix}`)).slice(0, 4096) }
}

export function digestTemplate(d: { overdue: number; sleeping: number; weakBlock: { label: string; score: number } | null }): TemplatePayload {
  const weak = d.weakBlock ? `${d.weakBlock.label} (${Math.round(d.weakBlock.score * 10) / 10})` : 'нет данных'
  return urlPayload('digest', [String(d.overdue), String(d.sleeping), sanitizeParam(weak, 120)], 'pulse')
}

export function expertNotificationTemplate(n: { title: string; lines: string[]; path?: string | null }): TemplatePayload {
  return urlPayload(
    'expert_notification',
    [sanitizeParam(n.title, 120), sanitizeParam(n.lines.join(' · '), 600, 'без подробностей')],
    urlSuffix(n.path, 'expert'),
  )
}

export function reportReviewTemplate(r: { title: string; version: number | string; date: string; client: string; path?: string | null }): TemplatePayload {
  return urlPayload(
    'report_review',
    [sanitizeParam(r.title, 120), sanitizeParam(String(r.version), 10), sanitizeParam(r.date, 20), sanitizeParam(r.client, 120, 'не указан')],
    urlSuffix(r.path, 'expert/reports'),
  )
}

export function staffAlertTemplate(n: { levelLabel: string; title: string; lines: string[]; path?: string | null }): TemplatePayload {
  return urlPayload(
    'staff_alert',
    [sanitizeParam(n.levelLabel, 40), sanitizeParam(n.title, 160), sanitizeParam(n.lines.join(' · '), 600, 'без подробностей')],
    urlSuffix(n.path, 'admin-giga-panel/notifications'),
  )
}

/** Authentication template: the code goes to the body and to the copy-code button. */
export function phoneVerificationTemplate(code: string): TemplatePayload {
  return {
    template: 'phone_verification',
    body: [code],
    buttons: [{ index: 0, text: code }],
    fallbackText: `Код подтверждения AIStart360: ${code}. Действует 10 минут. Никому не сообщайте этот код.`,
  }
}
