export const TEMPLATE_IDS = Object.keys(TEMPLATES) as TemplateId[]

export function getTemplate(id: TemplateId | string): SafeTemplate | null {
  return (TEMPLATES as Record<string, SafeTemplate>)[id] ?? null
}

/** Render a template, substituting {placeholders}; unknown placeholders → ''. */
export function renderTemplate(id: TemplateId | string, vars: Record<string, string> = {}): string {
  const t = getTemplate(id)
  if (!t) return ''
  return t.text.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '')
}
