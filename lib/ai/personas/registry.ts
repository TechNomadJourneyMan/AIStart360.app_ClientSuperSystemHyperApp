const BY_ID = new Map(PERSONAS.map((p) => [p.id, p]))

export const PERSONA_IDS = PERSONAS.map((p) => p.id)

export function listPersonas(): GriPersona[] {
  return PERSONAS
}

/** Persona by id, falling back to the base persona for unknown/empty ids. */
export function getPersona(id: string | null | undefined): GriPersona {
  return (id && BY_ID.get(id)) || BY_ID.get(DEFAULT_PERSONA_ID)!
}

/** Personas available on a given tariff tier. */
export function listAvailablePersonas(tier: 'free' | 'pro'): GriPersona[] {
  return tier === 'pro' ? PERSONAS : PERSONAS.filter((p) => p.tier === 'free')
}

/** The system-prompt fragment for a persona (base persona for unknown ids). */
export function personaBlock(id: string | null | undefined): string {
  return getPersona(id).promptBlock
}
