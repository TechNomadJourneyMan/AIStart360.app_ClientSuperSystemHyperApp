/**
 * lib/survey/where-to-find.ts — «где взять цифру / как ответить» для вопросов
 * анкеты клиента (спека docs/superpowers/specs/2026-10-23-survey-three-modes-design.md,
 * §8.5, §8.10, фазы Ф4/Ф5).
 *
 * ВНИМАНИЕ: КОНТЕНТ ТРЕБУЕТ ПРОВЕРКИ ЭКСПЕРТОМ (спека §8.5: «пишет команда, проверяет
 * эксперт»). Пока эксперт не подтвердил запись, считайте её черновиком.
 * Особенно проверить: номера счетов 1С, названия форм и налоговых режимов РК
 * (с 2026 года действует новый Налоговый кодекс), пути меню в 1С, Kaspi,
 * amoCRM и Битрикс24.
 *
 * Где используется:
 *  • строка `short` — подсказка под полем (режимы 1 и 2);
 *  • `how`, `sources`, `ifUnknown`, `example` — кнопка «Где взять цифру?»
 *    у «Помощника» (без ИИ) и единственный источник знаний ИИ-беседы о том,
 *    откуда брать данные (ИИ не придумывает источники сам, §8.5).
 *
 * Правила текста (решения PO):
 *  • простые слова, термин — только с пояснением;
 *  • бизнес в Казахстане: ₸, 1С, Kaspi, amoCRM / Битрикс24, ИП / ТОО;
 *  • никаких норм, «средних по рынку» и сравнений с другими компаниями —
 *    сравнение появится позже, после проверки экспертом (§9.4);
 *  • в `sources` — только то, в чём уверены; где не уверены — общими словами,
 *    без выдуманных номеров строк и пунктов меню;
 *  • `short` ≤ 90 символов.
 *
 * Ключи — те же, что в `survey_answers` (`lib/survey/steps.ts`). Авто-ключи
 * «год = месяц × 12» сюда не входят: их считает форма. Тест-сторож:
 * tests/unit/survey/where-to-find.test.ts.
 */

export interface WhereToFind {
  /** Одна строка под полем, ≤ 90 символов. */
  short: string
  /** 2–4 простых предложения: что значит цифра, как посчитать, частые ошибки. */
  how: string
  /** Где именно найти: программа, отчёт, документ. */
  sources: string[]
  /** Как прикинуть, если точной цифры нет, и что значит «не знаю» для результата. */
  ifUnknown: string
  /** Пример расчёта на условных цифрах (не норма и не сравнение). */
  example?: string
}

